"""Font encoding vector utilities."""

import re


def read_encoding(path):
    """Read a PostScript encoding file, returning a list of glyph names."""
    with open(path, "r", encoding="latin-1") as f:
        enc = f.read()
    m = re.search(r"(/[^ ]+)\s+\[", enc)
    if m is None:
        raise ValueError(f"Could not find encoding array in {path}")
    return re.findall(r"(/[^ \n\r\t]+)[ \n\r\t]", enc[m.end():])


def glyph_set_for_chars(encoding, chars):
    """Return a set of glyph names for the given character indices."""
    return {encoding[c] for c in chars if c < len(encoding)}


